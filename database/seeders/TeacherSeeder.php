<?php

namespace Database\Seeders;

use App\Models\Role;
use App\Models\User;
use Illuminate\Database\Seeder;
use Illuminate\Support\Facades\Hash;

class TeacherSeeder extends Seeder
{
    /*
    |--------------------------------------------------------------------------
    | المواد
    |--------------------------------------------------------------------------

    |
    | 1  = الفيزياء
    | 2  = الكيمياء
    | 3  = اللغة العربية
    | 4  = التاريخ
    | 5  = الجغرافيا
    | 6  = الرياضيات
    | 7  = اللغة الإنجليزية
    | 8  = اللغة الفرنسية
    | 9  = التربية الدينية
    | 10 = علم الأحياء
    | 11 = التربية الرياضية
    | 12 = التربية الفنية
    |
    */

    private const SUBJECTS = [
        1  => 'الفيزياء',
        2  => 'الكيمياء',
        3  => 'اللغة العربية',
        4  => 'التاريخ',
        5  => 'الجغرافيا',
        6  => 'الرياضيات',
        7  => 'اللغة الإنجليزية',
        8  => 'اللغة الفرنسية',
        9  => 'التربية الدينية',
        10 => 'علم الأحياء',
        11 => 'التربية الرياضية',
        12 => 'التربية الفنية',
    ];

    private const SECTION_IDS = [
        1,
        2,
        3,
        4,
        5,
        6,
        7,
        8,
        9,
    ];

    public function run(): void
    {
        $role = Role::query()
            ->where('name', 'teacher')
            ->firstOrFail();

        /*
        |--------------------------------------------------------------------------
        | أسماء المعلمين
        |--------------------------------------------------------------------------
        |
        | لدينا عدد أكبر من المعلمين من عدد الشعب لكل مادة،
        | حتى يكون من الطبيعي أن يدرّس المعلم شعبة أو شعبتين
        | أو أكثر، بحسب التوزيع العشوائي.
        |
        */

        $teacherNames = [
            ['أحمد', 'علي'],
            ['عمر', 'خالد'],
            ['سارة', 'محمد'],
            ['لينا', 'أحمد'],
            ['حسن', 'علي'],
            ['نور', 'يوسف'],
            ['ريم', 'عمر'],
            ['فادي', 'حسن'],
            ['مايا', 'علي'],
            ['تالا', 'يوسف'],
            ['كريم', 'حسن'],
            ['رنا', 'محمود'],
            ['علي', 'حسن'],
            ['منى', 'علي'],
            ['خالد', 'عمر'],
            ['نور', 'أحمد'],
            ['سامي', 'إبراهيم'],
            ['رنا', 'يوسف'],
            ['يارا', 'محمود'],
            ['باسل', 'علي'],
            ['هدى', 'عمر'],
            ['زيد', 'حسن'],
            ['سامر', 'خالد'],
            ['ديما', 'علي'],
            ['ربى', 'علي'],
            ['جنى', 'عمر'],
            ['يوسف', 'علي'],
            ['جاد', 'محمود'],
            ['لمى', 'خالد'],
            ['نبيل', 'حسن'],
            ['سلمى', 'أحمد'],
            ['آدم', 'خالد'],
            ['لين', 'محمد'],
            ['تامر', 'علي'],
            ['رامي', 'حسن'],
            ['داليا', 'عمر'],
            ['نادر', 'علي'],
            ['هالة', 'حسن'],
            ['سمير',  'عمر'],
            ['ريما',  'أحمد'],
            ['وليد', 'خالد'],
            ['سحر', 'علي'],
            ['ماهر',  'حسن'],
            ['آية',  'عمر'],
            ['طارق', 'محمود'],
            ['مريم',  'خالد'],
            ['إياد', 'حسن'],
            ['رشا',  'علي'],
        ];


        $nameIndex = 0;

        foreach (self::SUBJECTS as $subjectId => $subjectName) {

            /*
            |--------------------------------------------------------------------------
            | خلط الشعب
            |--------------------------------------------------------------------------
            |
            | كل مادة ستأخذ الشعب بترتيب عشوائي.
            |
            */

            $sections = self::SECTION_IDS;
            shuffle($sections);

            /*
            |--------------------------------------------------------------------------
            | تقسيم الشعب على المعلمين
            |--------------------------------------------------------------------------
            |
            | عدد المعلمين لهذه المادة سيكون بين 2 و 4.
            |
            | مثال:
            |
            | المعلم A → شعبتان
            | المعلم B → شعبة
            | المعلم C → شعبتان
            | المعلم D → 4 شعب
            |
            | المهم أن جميع الشعب التسع تحصل على تكليف.
            |
            */

            $teacherCount = random_int(2, 4);

            /*
            |--------------------------------------------------------------------------
            | نضمن أن عدد المعلمين لا يتجاوز عدد الشعب.
            |--------------------------------------------------------------------------
            */

            $teacherCount = min(
                $teacherCount,
                count($sections)
            );

            /*
            |--------------------------------------------------------------------------
            | إنشاء المعلمين لهذه المادة
            |--------------------------------------------------------------------------
            */

            $teachers = [];

            for ($i = 0; $i < $teacherCount; $i++) {

                if (! isset($teacherNames[$nameIndex])) {
                    throw new \RuntimeException(
                        'انتهت أسماء المعلمين المتاحة في TeacherSeeder.'
                    );
                }

                [$firstName, $lastName] = $teacherNames[$nameIndex];

                $phoneNumber = 1000000 + $nameIndex + 1;

                $user = User::create([
                    'first_name' => $firstName,
                    'last_name' => $lastName,
                    'phone' => '09' . $phoneNumber,
                    'code' => $this->generateUserCode('T'),
                    'password' => Hash::make('123456'),
                    'role_id' => $role->id,
                ]);

                $teacher = $user->teacher()->create([]);

                $teachers[] = $teacher;

                $nameIndex++;
            }

            /*
            |--------------------------------------------------------------------------
            | توزيع الشعب على المعلمين
            |--------------------------------------------------------------------------
            |
            | نوزع كل شعبة على معلم.
            |
            | لا نستخدم modulo فقط، بل نخلط ترتيب المعلمين
            | حتى يكون التوزيع غير ثابت.
            |
            */

            shuffle($teachers);

            foreach ($sections as $index => $sectionId) {

                $teacher = $teachers[$index % count($teachers)];

                $teacher->assignments()->create([
                    'section_id' => $sectionId,
                    'subject_id' => $subjectId,
                ]);
            }
        }
    }

    /*
    |--------------------------------------------------------------------------
    | توليد رمز مستخدم المعلم
    |--------------------------------------------------------------------------
    */

    private function generateUserCode(string $prefix): string
    {
        $lastUser = User::query()
            ->where('code', 'like', $prefix . '%')
            ->orderByDesc('id')
            ->first();

        if (! $lastUser) {
            return $prefix . '1001';
        }

        $lastNumber = (int) substr(
            $lastUser->code,
            strlen($prefix)
        );

        return $prefix . ($lastNumber + 1);
    }
}